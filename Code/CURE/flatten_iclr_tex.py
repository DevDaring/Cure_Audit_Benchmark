"""
File: Code/CURE/flatten_iclr_tex.py
Purpose: Produce a self-contained copy of the ICLR manuscript for the Paper_Writing revision
         loop (and for Overleaf if wanted): every \\input{tables_v2/...} is inlined and every
         number macro from tables_v2/numbers_v2.tex is expanded to its literal value, so the
         reviewers and the mechanical checkers see the real tables and numbers. The reverse
         script (unflatten) restores the \\input lines for the generated tables after the
         revision, keyed on \\label{tab:...}, so the tables stay generated.

Usage:
  python Code/CURE/flatten_iclr_tex.py flatten  <src.tex> <dst.tex>
  python Code/CURE/flatten_iclr_tex.py unflatten <revised.tex> <dst.tex>
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve()
ICLR = HERE.parents[2] / "Submission2" / "iclr2027"
TABLES = ICLR / "tables_v2"
HEADER = "%% generated by Code/CURE/make_iclr_tables_v2.py -- do not edit by hand\n"


def macros() -> dict:
    out = {}
    for line in (TABLES / "numbers_v2.tex").read_text(encoding="utf-8").splitlines():
        m = re.match(r"\\newcommand\{\\([A-Za-z]+)\}\{(.*)\}$", line.strip())
        if m:
            out[m.group(1)] = m.group(2)
    return out


def flatten(src: Path, dst: Path) -> None:
    tex = src.read_text(encoding="utf-8")
    # drop the macro input line; expand macros, longest names first
    tex = tex.replace("\\input{tables_v2/numbers_v2}\n", "")
    for name, val in sorted(macros().items(), key=lambda kv: -len(kv[0])):
        tex = re.sub(r"\\" + name + r"(?![A-Za-z])(\{\})?", lambda m, v=val: v, tex)

    def inline(m):
        body = (TABLES / (m.group(1) + ".tex")).read_text(encoding="utf-8").replace(HEADER, "")
        return "%% BEGIN GENERATED %s\n%s%% END GENERATED %s" % (m.group(1), body.rstrip("\n") + "\n", m.group(1))
    tex = re.sub(r"\\input\{tables_v2/([A-Za-z0-9_]+)\}", inline, tex)
    dst.write_text(tex, encoding="utf-8")
    print("flattened -> %s (%d macros, tables inlined)" % (dst, len(macros())))


def unflatten(src: Path, dst: Path) -> None:
    """Restore \\input for every generated table, keyed on its label; prose numbers stay literal."""
    tex = src.read_text(encoding="utf-8")
    labels = {}
    for f in sorted(TABLES.glob("tab_*.tex")):
        m = re.search(r"\\label\{([^}]+)\}", f.read_text(encoding="utf-8"))
        if m:
            labels[m.group(1)] = f.stem
    n = 0
    for lab, stem in labels.items():
        inside = r"(?:(?!\\end\{table\})(?!\\begin\{table\}).)*?"      # stay within one table environment
        pat = re.compile(r"(?:%% BEGIN GENERATED " + stem + r"\n)?\\begin\{table\}" + inside + r"\\label\{" + re.escape(lab) + r"\}" + inside + r"\\end\{table\}\n(?:%% END GENERATED " + stem + r"\n?)?", re.S)
        tex, k = pat.subn("\\\\input{tables_v2/%s}\n" % stem, tex, count=1)
        n += k
    if "\\input{tables_v2/numbers_v2}" not in tex:
        tex = tex.replace("\\begin{document}", "\\input{tables_v2/numbers_v2}\n\n\\begin{document}", 1)
    dst.write_text(tex, encoding="utf-8")
    print("unflattened -> %s (%d tables restored to \\input)" % (dst, n))


if __name__ == "__main__":
    cmd, a, b = sys.argv[1], Path(sys.argv[2]), Path(sys.argv[3])
    (flatten if cmd == "flatten" else unflatten)(a, b)
