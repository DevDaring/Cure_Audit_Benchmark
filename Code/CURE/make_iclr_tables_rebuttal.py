def flip_series(m, cond):
    d = ROWS[m]
    g = d[(d.kind == "score") & (d.status == "ok") & (d.group == "final") & (d.cond == cond)]
    a, b = g[g.side == "A"].set_index("seed_id"), g[g.side == "B"].set_index("seed_id")
    j = a[["gen_idx", "gen_valid"]].join(b[["gen_idx", "gen_valid"]], rsuffix="_b", how="inner")
    j = j[(j.gen_valid == True) & (j.gen_valid_b == True)]  # noqa: E712
    return (j.gen_idx != j.gen_idx_b).astype(float)


def flip_test(m, cond):
    x = pd.concat([flip_series(m, "B").rename("b"), flip_series(m, cond).rename("c")], axis=1).dropna()
    r = H.paired((x.b - x.c).to_numpy(), TMPL[m].reindex(x.index).to_numpy())
    r["level_b"] = float(x.b.mean())
    r["level_c"] = float(x.c.mean())
    return r


def rewrite_levels(m):
    h4 = pd.read_parquet(R / ("h4_rewrite_%s.parquet" % m))
    ok = h4[(h4.kind == "score") & (h4.status == "ok")]
    pt = H.pair_table(ok)
    out = {}
    q1 = ROWS[m]
    q1 = q1[(q1.kind == "score") & (q1.status == "ok") & (q1.cond == "P_span@1")].set_index(["seed_id", "side"]).q
    qb = ok[ok.cond == "B"].set_index(["seed_id", "side"]).q
    for grp in ("final", "control"):
        for cond in ("B", "RW"):
            g = pt[(pt.group == grp) & (pt.cond == cond)]
            lv = H.level(g.acc.to_numpy(), g.template.to_numpy())
            out[(grp, cond, "acc")] = lv["estimate"]
            out[(grp, cond, "T")] = H.level(g["T"].to_numpy(), g.template.to_numpy())["estimate"]
        recs = []
        for r in ok[(ok.cond == "RW") & (ok.group == grp)].itertuples(index=False):
            k = (r.seed_id, r.side)
            if k in q1.index and k in qb.index:
                q = np.asarray(json.loads(r.q))
                recs.append({"t": r.template, "s": r.seed_id, "e": 0.5 * np.abs(np.asarray(json.loads(q1[k])) - q).sum(), "b": 0.5 * np.abs(np.asarray(json.loads(qb[k])) - q).sum()})
        x = pd.DataFrame(recs).groupby(["t", "s"]).mean().groupby("t").mean()
        out[(grp, "TV_edit")] = float(x.e.mean())
        out[(grp, "TV_base")] = float(x.b.mean())
    out["identical"] = float(ok[ok.cond == "RW"].identical_after_rewrite.mean())
    return out


