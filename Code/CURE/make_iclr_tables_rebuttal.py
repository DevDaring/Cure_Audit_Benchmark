"""
make_iclr_tables_rebuttal.py -- every table, figure and prose number of the revised ICLR 2027 manuscript
that comes from the equal-energy runs. Single entry point; CPU; reads stored rows only, trains nothing.

  python Code/CURE/make_iclr_tables_rebuttal.py

Sources: results/rebuttal_20261107/ (h_tests.csv, h_levels.csv, h_k5.csv, h_k8_tokens.csv, h9_bridge_*.csv,
h_exploratory.txt, h1/h4 parquet rows) and the frozen tables of Submission2/iclr2027/tables_v2/, copied with
the manuscript's plain terms.
Output: Submission2/iclr2027_rebuttal/{tables_v3,figures}/ with numbers_v3.tex and number_provenance_v3.csv.

Statistics follow Efron and Tibshirani (1993) and Holm (1979): studentised bootstrap over BBQ templates,
through hh_common.paired and hh_common.level. Comparisons computed here and absent from h_tests.csv are
marked exploratory in the manuscript. Implements the total-variation sensitivity and the patching effect
of Vig et al. (2020) and Zhang and Nanda (2024), as defined in the manuscript's Method section.
"""

