def tolerance_check():
    """Exploratory: the site tests again after dropping every pair with a scored row beyond 5% of its energy target."""
    same = total = 0
    for m in MODELS:
        d = ROWS[m]
        s = d[(d.kind == "score") & (d.status == "ok") & (d.group == "final")]
        x = s[(s.target_energy > 0) & (s.feasible == True)].copy()  # noqa: E712
        x["bad"] = ~(x.energy_per_pass / x.target_energy).between(.95, 1.05)
        bad = x[x.bad].groupby("cond").seed_id.apply(set).to_dict()
        for readout in ("T", "abs_C_answer"):
            w = wide(m, "final", "T") if readout == "T" else BR[m].abs()
            ps, rows = [], []
            for other, span in (("P_ne@1", "P_span@E(P_ne)"), ("P_last@1", "P_span@E(P_last)"), ("P_all@1", "P_span@1")):
                j = w[[other, span]].dropna()
                j = j[~j.index.isin(bad.get(other, set()) | bad.get(span, set()))]
                r = H.paired((j[other] - j[span]).to_numpy(), TMPL[m].reindex(j.index).to_numpy(), alternative="greater")
                ps.append(r["p"])
                rows.append(other)
            order = np.argsort(ps)
            hp = [0.0] * 3
            run = 0.0
            for rank, i in enumerate(order):
                run = max(run, min(1.0, (3 - rank) * ps[i]))
                hp[i] = run
            for other, p_h in zip(rows, hp):
                old = t(m, "K1_f1", readout, other).verdict == "supported"
                same += int((p_h < 0.05) == old)
                total += 1
    M("tolSame", str(same), "exploratory: K1 after dropping out-of-tolerance pairs")
    M("tolTotal", str(total), "exploratory")
    M("phiValidCtrl", f2(lev("phi-4-mini-instruct", "P_span@1", "validity", "control")), "h_levels control validity")
    print("tolerance", same, total)


