def wide(m, group, col):
    p = PT[m][PT[m].group == group]
    return p.pivot_table(index="seed_id", columns="cond", values=col, aggfunc="first")


def diff_test(m, group, col, plus, minus):
    w = wide(m, group, col)
    j = w[[plus, minus]].dropna()
    return H.paired((j[plus] - j[minus]).to_numpy(), TMPL[m].reindex(j.index).to_numpy())


def rule_rows(m):
    h9 = pd.read_csv(R / ("h9_bridge_%s.csv" % m))
    base = BR[m]["B"].abs().reindex(h9.seed_id).to_numpy()
    tm = TMPL[m].reindex(h9.seed_id).to_numpy()
    out = {}
    for lab, mask in (("all", np.ones(len(h9), bool)), ("equal", h9.equal.to_numpy()), ("unequal", ~h9.equal.to_numpy())):
        rec = {"n": int(mask.sum())}
        for rule, col in (("whole", "this"), ("trunc", "sept")):
            a = np.abs(h9[col].to_numpy()[mask])
            rec[rule + "_R"] = 100 * (1 - a.mean() / np.nanmean(base[mask]))
            rec[rule + "_test"] = H.paired(base[mask] - a, tm[mask])
        out[lab] = rec
    return out


