def w(name, body):
    OUT.mkdir(parents=True, exist_ok=True)
    cap, lab, place = CAPTIONS[name]
    wrapped = "\n".join(["\\begin{table}[%s]" % place, "\\caption{%s}" % cap, "\\label{%s}" % lab, "\\centering\\footnotesize",
                         "\\begin{adjustbox}{max width=\\textwidth}", body, "\\end{adjustbox}", "\\end{table}"])
    (OUT / name).write_text("%% generated by Code/CURE/make_iclr_tables_feedback.py -- do not edit by hand\n" + wrapped + "\n", encoding="utf-8")
    print("  wrote tables_v2/%s" % name)


def ci(v, lo, hi, f="%.3f"):
    return "%s {\\scriptsize[%s, %s]}" % (f % v, f % lo, f % hi)


def pfmt(p):
    if not np.isfinite(p):
        return "--"
    return "$<$0.001" if p < 0.001 else "%.3f" % p


def pct(x, nd=0):
    v = round(float(x), nd)
    if v == 0:
        v = 0.0                                   # no "-0"
    return ("%%.%df" % nd) % v


