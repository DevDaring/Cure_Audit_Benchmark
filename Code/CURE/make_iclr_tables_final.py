def prov(t, q, s):
    PROV.append({"float": t, "quantity": q, "source_file": s})


def w(name, body):
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / name).write_text("%% generated by Code/CURE/make_iclr_tables_final.py -- do not edit by hand\n" + body, encoding="utf-8")
    print("  wrote tables_v2/%s" % name)


def cell(v, lo, hi, f="%.3f"):
    return "%s {\\scriptsize[%s, %s]}" % (f % v, f % lo, f % hi)


