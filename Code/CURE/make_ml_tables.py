"""
File: Code/CURE/make_ml_tables.py
Purpose: Generate every LaTeX float for the Springer *Machine Learning* submission from the
         saved result files, so no number in the manuscript is typed by hand.

Comparison set. The eight published debiasing methods in BASELINES are the ones this study
evaluates against. The head-to-head is presented as what the audit signal buys and what it
costs, never as a claim of superiority over all known methods, and the prose states that the
set is not exhaustive.

Every table writes its provenance into number_provenance.csv.

Usage:
  python Code/CURE/make_ml_tables.py
  python Code/CURE/make_ml_tables.py --out ../../Submission2

Part of the CURE codebase (Springer Machine Learning submission).
"""

import argparse
import json
import logging
from pathlib import Path

import numpy as np
import pandas as pd

log = logging.getLogger("ml_tables")

ROOT = Path(__file__).resolve().parents[2]
CURE_R = ROOT / "Code" / "CURE" / "results"
AUDIT_R = ROOT / "Code" / "audit" / "results"
RE = CURE_R / "reanalysis"

MODELS = ["llama-3.1-8b-instruct", "qwen2.5-7b-instruct",
          "gemma-2-2b-it", "phi-4-mini-instruct"]
DISPLAY = {"llama-3.1-8b-instruct": "Llama-3.1-8B", "qwen2.5-7b-instruct": "Qwen2.5-7B",
           "gemma-2-2b-it": "Gemma-2-2B", "phi-4-mini-instruct": "Phi-4-mini"}

# The eight published methods this study compares against, plus CURE itself.
BASELINES = [
    ("cure", "CURE (audit-guided)"),
    ("prompt_debias", "Self-Debias"),
    ("generic_erase", "GenericErase"),
    ("meandiff_steer", "MeanDiff steering"),
    ("fairsteer", "FairSteer"),
    ("biasgym", "BiasGym"),
    ("sae_debias", "SAE-Debias"),
    ("hsal", "H-SAL"),
    ("nofreelunch", "LogitSteer"),
]
EXCLUDED = {"patchscopes"}

PROV: list[dict] = []


def _prov(float_name: str, quantity: str, src: Path) -> None:
    PROV.append({"float": float_name, "quantity": quantity,
                 "source_file": str(src.relative_to(ROOT)).replace("\\", "/")})


def _tbl(label: str, caption: str, body: str, star: bool = False) -> str:
    env = "table*" if star else "table"
    return (f"%% generated by Code/CURE/make_ml_tables.py -- do not edit by hand\n"
            f"\\begin{{{env}}}[t]\n\\caption{{{caption}}}\\label{{{label}}}%\n"
            f"\\centering\n\\begin{{tabular*}}{{\\textwidth}}{{@{{\\extracolsep{{\\fill}}}}"
            f"{body}\n\\end{{tabular*}}\n\\end{{{env}}}\n")


def _raw(label: str, caption: str, body: str, star: bool = False) -> str:
    """A plain tabular float wrapped so a wide table shrinks instead of overflowing.

    sn-jnl sets a narrower text block than the ACL style these tables were first written
    for, so the wide ones need scaling rather than a smaller font alone.
    """
    # sn-jnl wraps the plain `table` environment in threeparttable, and an adjustbox around
    # the tabular breaks that grouping. Only the wide `table*` floats are shrunk; the narrow
    # ones are emitted bare, which is what the class expects.
    if star:
        inner = (f"\\begin{{adjustbox}}{{max width=\\textwidth}}\n{body}\n"
                 f"\\end{{adjustbox}}")
        env = "table*"
    else:
        inner = body
        env = "table"
    return (f"%% generated by Code/CURE/make_ml_tables.py -- do not edit by hand\n"
            f"\\begin{{{env}}}[t]\n\\caption{{{caption}}}\\label{{{label}}}%\n"
            f"\\centering\\footnotesize\n{inner}\n\\end{{{env}}}\n")


# ---------------------------------------------------------------------------
# 0. Protocol: which split does which job
# ---------------------------------------------------------------------------
def table_protocol(out: Path) -> dict:
    """One place a reviewer can check that selection and evaluation are separated.

    Counts come from the result files rather than from the prose, so the table cannot drift
    away from what was actually run.
    """
    prog = pd.read_parquet(CURE_R / f"cure_prognosis_{MODELS[0]}.parquet")
    final = pd.read_parquet(CURE_R / f"cure_final_{MODELS[0]}.parquet")
    extra = pd.read_parquet(CURE_R / f"tacl_extra_{MODELS[0]}.parquet")
    rc = pd.read_csv(RE / "rank_curve.csv")
    _prov("tab:protocol", "seed and pair counts per split", CURE_R / "cure_final_llama-3.1-8b-instruct.parquet")
    _prov("tab:protocol", "prognosis seed count", CURE_R / f"cure_prognosis_{MODELS[0]}.parquet")

    n_pairs = int(final.n_pairs.max())
    n_test = int(extra.n_test_pairs.max())
    n_acc = int(extra.n_acc_seeds.max())
    ranks = sorted(rc["rank"].unique())

    rows = [
        ("Subspace estimate", "benchmark-stratified pairs", "SVD basis per layer"),
        ("Rank selection", f"{n_pairs} pairs, ranks {{{', '.join(map(str, ranks))}}}",
         "most signal removed within a 0.15 utility budget"),
        ("Head-to-head", f"{n_pairs} pairs, separate draw", "Table~\\ref{tab:h2h}"),
        ("Held-out removal", f"{n_test} pairs, disjoint seed split", "Table~\\ref{tab:behav}"),
        ("Behavioural readout", f"{n_acc} seeds per model", "accuracy and answer-flip rate"),
        ("Cost forecasting", f"{len(prog)} seeds per model",
         "split-half, threshold fitted on one half"),
    ]
    lines = [r"\begin{tabular}{lll}", r"\toprule",
             r"Stage & Data & Role \\", r"\midrule"]
    for a, b, c in rows:
        lines.append(f"{a} & {b} & {c} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]

    cap = "Which data each stage uses, and what each stage decides."
    (out / "tab_protocol.tex").write_text(
        _raw("tab:protocol", cap, "\n".join(lines), star=True), encoding="utf-8")
    return {"n_prog": len(prog), "ranks": ranks}


# ---------------------------------------------------------------------------
# 1. The audit: validity gap per benchmark
# ---------------------------------------------------------------------------
def table_gap(out: Path) -> dict:
    src = AUDIT_R / "validity_gap_leaderboard.parquet"
    d = pd.read_parquet(src)
    d = d[d.model_name.isin(MODELS)].dropna(subset=["validity_gap"])
    _prov("tab:gap", "native and audit-robust pass rate per benchmark", src)

    bench = [("bbq", "BBQ"), ("crows_pairs", "CrowS-Pairs"), ("stereoset", "StereoSet")]
    bench = [(k, v) for k, v in bench if k in set(d.benchmark)]

    lines = [r"\begin{tabular}{l" + "rr" * len(bench) + "}", r"\toprule",
             "Model & " + " & ".join(rf"\multicolumn{{2}}{{c}}{{{v}}}" for _, v in bench)
             + r" \\"]
    cm = " ".join(rf"\cmidrule(lr){{{2+2*i}-{3+2*i}}}" for i in range(len(bench)))
    lines += [cm, " & " + " & ".join(["native & audited"] * len(bench)) + r" \\", r"\midrule"]
    for m in MODELS:
        cells = []
        for k, _ in bench:
            r = d[(d.model_name == m) & (d.benchmark == k)]
            if r.empty:
                cells += ["--", "--"]
            else:
                cells += [f"{r.native_pass_rate.iloc[0]:.2f}",
                          f"{r.mirage_full_pass_rate.iloc[0]:.2f}"]
        lines.append(f"{DISPLAY[m]} & " + " & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]

    cap = "Native benchmark pass rate against the causal-audit-robust rate, per benchmark."
    (out / "tab_gap.tex").write_text(_raw("tab:gap", cap, "\n".join(lines), star=True),
                                     encoding="utf-8")
    worst = d.loc[d.validity_gap.idxmax()]
    return {"max_gap": float(worst.validity_gap), "max_model": DISPLAY[worst.model_name],
            "max_bench": worst.benchmark}


# ---------------------------------------------------------------------------
# 2. The head-to-head, with utility read jointly
# ---------------------------------------------------------------------------
def table_headtohead(out: Path) -> dict:
    rows = {}
    for m in MODELS:
        src = CURE_R / f"cure_final_{m}.parquet"
        f = pd.read_parquet(src)
        _prov("tab:h2h", f"bias removed and utility cost, {DISPLAY[m]}", src)
        rows[m] = f.set_index("method")

    lines = [r"\begin{tabular}{l" + "rr" * len(MODELS) + "}", r"\toprule",
             "Method & " + " & ".join(rf"\multicolumn{{2}}{{c}}{{{DISPLAY[m]}}}"
                                      for m in MODELS) + r" \\"]
    cm = " ".join(rf"\cmidrule(lr){{{2+2*i}-{3+2*i}}}" for i in range(len(MODELS)))
    lines += [cm, " & " + " & ".join([r"removed & cost"] * len(MODELS)) + r" \\", r"\midrule"]
    for key, label in BASELINES:
        cells = []
        for m in MODELS:
            g = rows[m]
            if key not in g.index:
                cells += ["--", "--"]
                continue
            r = g.loc[key]
            cells += [f"{r.causal_residual_removed:.3f}",
                      f"{r.utility_cost:+.3f}" if r.utility_cost == r.utility_cost else "--"]
        name = rf"\textbf{{{label}}}" if key == "cure" else label
        lines.append(f"{name} & " + " & ".join(cells) + r" \\")
        if key == "cure":
            lines.append(r"\midrule")
    lines += [r"\bottomrule", r"\end{tabular}"]

    cap = "Causal signal removed and the utility cost of removing it, per method."
    (out / "tab_h2h.tex").write_text(_raw("tab:h2h", cap, "\n".join(lines), star=True),
                                     encoding="utf-8")

    cure_costs = {m: float(rows[m].loc["cure"].utility_cost) for m in MODELS
                  if "cure" in rows[m].index}
    return {"cure_utility_cost": cure_costs}


# ---------------------------------------------------------------------------
# 3. Held-out causal removal and the behavioural readout
# ---------------------------------------------------------------------------
def table_behaviour(out: Path) -> dict:
    recs = []
    for m in MODELS:
        src = CURE_R / f"tacl_extra_{m}.parquet"
        t = pd.read_parquet(src)
        _prov("tab:behav", f"held-out removal, accuracy and flip rate, {DISPLAY[m]}", src)
        for _, r in t.iterrows():
            if r.method in EXCLUDED:
                continue
            recs.append({"model": m, "method": r.method,
                         "heldout": r.heldout_residual_removed,
                         "acc": r.behav_accuracy, "flip": r.behav_flip_rate})
    d = pd.DataFrame(recs)

    # All four models appear, because the prose makes a claim about all four. An earlier
    # version showed two, which a reader could only read as the other two being unfavourable.
    order = [("unedited", "Unedited model"), ("cure", "CURE (audit-guided)"),
             ("generic_erase", "GenericErase"), ("sae_debias", "SAE-Debias")]
    lines = [r"\begin{tabular}{l" + "rrr" * len(MODELS) + "}", r"\toprule",
             "Method & " + " & ".join(rf"\multicolumn{{3}}{{c}}{{{DISPLAY[m]}}}"
                                      for m in MODELS) + r" \\"]
    cm = " ".join(rf"\cmidrule(lr){{{2+3*i}-{4+3*i}}}" for i in range(len(MODELS)))
    lines += [cm,
              " & " + " & ".join([r"removed & acc. & flip"] * len(MODELS)) + r" \\",
              r"\midrule"]
    for key, label in order:
        cells = []
        for m in MODELS:
            r = d[(d.model == m) & (d.method == key)]
            if r.empty:
                cells += ["--", "--", "--"]
            else:
                r = r.iloc[0]
                rm = "--" if key == "unedited" else f"{r.heldout:.3f}"
                cells += [rm, f"{r.acc:.3f}", f"{r.flip:.3f}"]
        name = rf"\textbf{{{label}}}" if key == "cure" else label
        lines.append(f"{name} & " + " & ".join(cells) + r" \\")
        if key == "unedited":
            lines.append(r"\midrule")
    lines += [r"\bottomrule", r"\end{tabular}"]

    n_seed = int(pd.read_parquet(CURE_R / f"tacl_extra_{MODELS[0]}.parquet")
                 .n_acc_seeds.max())
    cap = (f"Held-out evaluation on {n_seed} seeds per model: causal signal removed, task "
           f"accuracy (higher better) and answer-flip rate (lower better).")
    (out / "tab_behav.tex").write_text(_raw("tab:behav", cap, "\n".join(lines), star=True),
                                       encoding="utf-8")

    c = d[(d.method == "cure")]
    u = d[(d.method == "unedited")]
    return {
        "cure_acc_drop": {DISPLAY[m]: float(u[u.model == m].acc.iloc[0]
                                            - c[c.model == m].acc.iloc[0]) for m in MODELS},
        "cure_flip_rise": {DISPLAY[m]: float(c[c.model == m].flip.iloc[0]
                                             - u[u.model == m].flip.iloc[0]) for m in MODELS},
    }


# ---------------------------------------------------------------------------
# 4. The rank curve, as measured
# ---------------------------------------------------------------------------
def table_rankcurve(out: Path) -> dict:
    src = RE / "rank_curve.csv"
    d = pd.read_csv(src)
    _prov("tab:rank", "bias removed and utility cost at every tested rank", src)

    ranks = sorted(d["rank"].unique())
    lines = [r"\begin{tabular}{l" + "rr" * len(ranks) + "}", r"\toprule",
             "Model & " + " & ".join(rf"\multicolumn{{2}}{{c}}{{$r={k}$}}" for k in ranks)
             + r" \\"]
    cm = " ".join(rf"\cmidrule(lr){{{2+2*i}-{3+2*i}}}" for i in range(len(ranks)))
    lines += [cm, " & " + " & ".join([r"removed & cost"] * len(ranks)) + r" \\", r"\midrule"]
    n_missing = 0
    for m in MODELS:
        cells = []
        for k in ranks:
            r = d[(d.model_name == m) & (d["rank"] == k)]
            if r.empty:
                cells += ["--", "--"]
                continue
            r = r.iloc[0]
            rm = f"{r.bias_removed:.3f}"
            if r.utility_cost != r.utility_cost:
                cells += [rm, r"n/m"]
                n_missing += 1
            else:
                star = r"$^{\ast}$" if r.is_operating_rank else ""
                cells += [rm, f"{r.utility_cost:+.3f}{star}"]
        lines.append(f"{DISPLAY[m]} & " + " & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]

    cap = (r"Causal signal removed and utility cost at each erasure rank. $^{\ast}$ marks the "
           r"selected operating rank; n/m marks a rank whose utility was not measured.")
    (out / "tab_rank.tex").write_text(_raw("tab:rank", cap, "\n".join(lines), star=True),
                                      encoding="utf-8")
    return {"n_unmeasured": n_missing}


# ---------------------------------------------------------------------------
# 5. Erasure cost is forecastable
# ---------------------------------------------------------------------------
def table_prognosis(out: Path) -> dict:
    s1 = RE / "prognosis_seed_level.csv"
    s2 = RE / "prognosis_heldout.csv"
    a = pd.read_csv(s1)
    b = pd.read_csv(s2)
    _prov("tab:prog", "Spearman, censoring, and separation of hard-to-erase seeds", s1)
    _prov("tab:prog", "split-half held-out separation", s2)
    m = a.merge(b, on="model_name", how="left")

    lines = [r"\begin{tabular}{lrrrrrr}", r"\toprule",
             r"Model & Seeds & Censored & Spearman $\rho$ & 95\% CI & "
             r"AUC & AUC \\",
             r" & & (\%) & & & in-sample & held-out \\", r"\midrule"]
    for mm in MODELS:
        r = m[m.model_name == mm]
        if r.empty:
            continue
        r = r.iloc[0]
        lines.append(
            f"{DISPLAY[mm]} & {int(r.n_seeds)} & {100*r.frac_censored:.1f} & "
            f"{r.spearman:.3f} & [{r.spearman_ci_lo:.2f}, {r.spearman_ci_hi:.2f}] & "
            f"{r.auc_hard:.3f} & {r.heldout_auc_mean:.3f} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]

    cap = "Predicting erasure cost from the audit score alone, in and out of sample."
    (out / "tab_prog.tex").write_text(_raw("tab:prog", cap, "\n".join(lines), star=True),
                                      encoding="utf-8")
    return {"auc_lo": float(a.auc_hard.min()), "auc_hi": float(a.auc_hard.max()),
            "ho_lo": float(b.heldout_auc_mean.min()), "ho_hi": float(b.heldout_auc_mean.max()),
            "rho_lo": float(a.spearman.min()), "rho_hi": float(a.spearman.max()),
            "cens_lo": float(a.frac_censored.min()), "cens_hi": float(a.frac_censored.max())}


# ---------------------------------------------------------------------------
# 6. The mechanism
# ---------------------------------------------------------------------------
def table_mechanism(out: Path) -> dict:
    src = CURE_R / "anomaly_diagnostic.json"
    j = json.loads(src.read_text(encoding="utf-8"))
    _prov("tab:mech", "single-direction erasure diagnostic", src)
    lines = [r"\begin{tabular}{lrrr}", r"\toprule",
             r"Model & Direction & Mean $|C|$ after & Fraction removed \\", r"\midrule"]
    for model, blk in j.items():
        sd = blk.get("erase_single_direction", {})
        for k, v in sorted(sd.items(), key=lambda kv: int(kv[0]))[:3]:
            lines.append(f"{DISPLAY.get(model, model)} & {k} & "
                         f"{v.get('mean_erased', float('nan')):.3f} & "
                         f"{v.get('reduced_frac', float('nan')):.3f} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    cap = "Erasing one direction at a time, on the two models without a utility-safe rank."
    (out / "tab_mech.tex").write_text(_raw("tab:mech", cap, "\n".join(lines)),
                                      encoding="utf-8")
    return {"models": list(j.keys())}


def main() -> None:
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(ROOT / "Submission2" / "tables"))
    args = ap.parse_args()
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)

    proto = table_protocol(out)
    gap = table_gap(out)
    h2h = table_headtohead(out)
    beh = table_behaviour(out)
    rank = table_rankcurve(out)
    prog = table_prognosis(out)
    mech = table_mechanism(out)

    pd.DataFrame(PROV).drop_duplicates().to_csv(RE / "number_provenance.csv", index=False)

    print(f"\nwrote {len(list(out.glob('*.tex')))} floats to {out}")
    print("\n--- facts the prose must match ---")
    print(f"largest validity gap: {gap['max_gap']:.3f} ({gap['max_model']} on {gap['max_bench']})")
    print(f"CURE utility cost: " +
          ", ".join(f"{DISPLAY[k]} {v:+.3f}" for k, v in h2h["cure_utility_cost"].items()))
    print(f"CURE accuracy drop: {beh['cure_acc_drop']}")
    print(f"CURE flip-rate rise: {beh['cure_flip_rise']}")
    print(f"unmeasured utility cells in the rank curve: {rank['n_unmeasured']}")
    print(f"prognosis: rho {prog['rho_lo']:.2f}-{prog['rho_hi']:.2f}, "
          f"AUC {prog['auc_lo']:.2f}-{prog['auc_hi']:.2f}, "
          f"held-out AUC {prog['ho_lo']:.2f}-{prog['ho_hi']:.2f}, "
          f"censoring {100*prog['cens_lo']:.1f}-{100*prog['cens_hi']:.1f}%")
    print(f"mechanism models: {mech['models']}")


if __name__ == "__main__":
    main()
