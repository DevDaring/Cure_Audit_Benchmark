def cluster_boot(x: np.ndarray, clusters: np.ndarray, n_boot=N_BOOT, seed=SEED):
    """seed-cluster percentile bootstrap of a mean (the same scheme as common.ratio_bootstrap)"""
    x = np.asarray(x, float); ok = np.isfinite(x); x, clusters = x[ok], np.asarray(clusters)[ok]
    if len(x) == 0:
        return np.nan, np.nan, np.nan
    u, inv = np.unique(clusters, return_inverse=True); k = len(u)
    s = np.bincount(inv, weights=x, minlength=k); n = np.bincount(inv, minlength=k).astype(float)
    rng = np.random.default_rng(seed); take = rng.integers(0, k, size=(n_boot, k))
    est = s[take].sum(1) / n[take].sum(1)
    return float(x.mean()), float(np.percentile(est, 2.5)), float(np.percentile(est, 97.5))


